class Hl7IntegrationRouterCatalogService:
    """
    High-performance registry and lookup service for HL7 v2.5 Integration Router protocols.
    Provides caching, age-bracket filtering, guideline resolution, and standard code lookup.
    """
    def __init__(self):
        self.protocols = CLINICAL_HL7INTEGRATIONROUTER_PROTOCOLS_CATALOG
        self._indexed_by_authority: Dict[str, List[Dict[str, Any]]] = {}
        self._build_indices()

    def _build_indices(self):
        for item in self.protocols.values():
            auth = item.get("guideline_authority", "UNKNOWN")
            if auth not in self._indexed_by_authority:
                self._indexed_by_authority[auth] = []
            self._indexed_by_authority[auth].append(item)

    def lookup_protocol_by_code(self, standard_code: str) -> Optional[Dict[str, Any]]:
        for p in self.protocols.values():
            if p.get("standard_code") == standard_code:
                return p
        return None

    def filter_protocols_by_age(self, patient_age: int) -> List[Dict[str, Any]]:
        results = []
        for p in self.protocols.values():
            min_age = p.get("minimum_age_years", 0)
            max_age = p.get("maximum_age_years", 120)
            if min_age <= patient_age <= max_age:
                results.append(p)
        return results

    def get_protocols_by_authority(self, authority: str) -> List[Dict[str, Any]]:
        return self._indexed_by_authority.get(authority, [])

    def get_total_catalog_size(self) -> int:
        return len(self.protocols)

    def export_catalog_metadata(self) -> Dict[str, Any]:
        return {
            "catalog_title": "HL7 v2.5 Integration Router Protocols",
            "category": "Hl7IntegrationRouter",
            "total_specifications": len(self.protocols),
            "authorities_represented": list(self._indexed_by_authority.keys()),
            "version": "2026.4.1",
        }
